import jsPDF from "jspdf";
import type { ItineraryDay } from "./supabase";

type TripMeta = {
  travelers: number;
  budget: number;
  totalCost: number;
};

export function exportItineraryPDF(destination: string, days: ItineraryDay[], meta: TripMeta) {
  const doc = new jsPDF();
  const pageWidth = doc.internal.pageSize.getWidth();
  const margin = 20;
  let y = 20;

  // Title
  doc.setFontSize(24);
  doc.setFont("helvetica", "bold");
  doc.setTextColor(79, 70, 229);
  doc.text(`${destination} Trip Itinerary`, margin, y);
  y += 10;

  // Subtitle
  doc.setFontSize(12);
  doc.setFont("helvetica", "normal");
  doc.setTextColor(100, 100, 100);
  doc.text(`Generated by Wanderly AI · ${new Date().toLocaleDateString()}`, margin, y);
  y += 10;

  // Meta info
  doc.setDrawColor(200, 200, 200);
  doc.line(margin, y, pageWidth - margin, y);
  y += 8;

  doc.setFontSize(11);
  doc.setTextColor(60, 60, 60);
  doc.text(`Travelers: ${meta.travelers}`, margin, y);
  doc.text(`Total Budget: $${meta.budget}`, margin + 80, y);
  doc.text(`Estimated Cost: $${meta.totalCost}`, margin + 160, y);
  y += 6;
  doc.text(`Duration: ${days.length} day${days.length !== 1 ? "s" : ""}`, margin, y);
  y += 10;

  // Days
  days.forEach((day) => {
    if (y > 270) {
      doc.addPage();
      y = 20;
    }

    // Day header
    doc.setFontSize(14);
    doc.setFont("helvetica", "bold");
    doc.setTextColor(124, 58, 237);
    doc.text(`Day ${day.day}: ${day.theme}`, margin, y);
    y += 6;

    doc.setFontSize(10);
    doc.setFont("helvetica", "normal");
    doc.setTextColor(120, 120, 120);
    doc.text(`Date: ${day.date}  |  Daily Cost: ~$${day.dailyCost}`, margin, y);
    y += 8;

    // Activities
    day.activities.forEach((act) => {
      if (y > 275) {
        doc.addPage();
        y = 20;
      }

      doc.setFontSize(11);
      doc.setFont("helvetica", "bold");
      doc.setTextColor(50, 50, 50);
      doc.text(`${act.time} - ${act.title}`, margin + 4, y);
      y += 5;

      doc.setFontSize(9);
      doc.setFont("helvetica", "normal");
      doc.setTextColor(100, 100, 100);

      const descLines = doc.splitTextToSize(act.description, pageWidth - margin * 2 - 4);
      doc.text(descLines, margin + 4, y);
      y += descLines.length * 4 + 1;

      doc.text(`Location: ${act.location}  |  Duration: ${act.duration}  |  Cost: ~$${act.cost}`, margin + 4, y);
      y += 7;
    });

    // Restaurant & accommodation
    if (y > 270) {
      doc.addPage();
      y = 20;
    }
    doc.setFontSize(10);
    doc.setFont("helvetica", "italic");
    doc.setTextColor(80, 80, 80);
    doc.text(`Dinner: ${day.restaurant}  |  Stay: ${day.accommodation}`, margin + 4, y);
    y += 10;
  });

  // Footer
  const pageCount = doc.getNumberOfPages();
  for (let i = 1; i <= pageCount; i++) {
    doc.setPage(i);
    doc.setFontSize(8);
    doc.setTextColor(180, 180, 180);
    doc.text(
      `Wanderly AI · Page ${i} of ${pageCount}`,
      pageWidth / 2,
      doc.internal.pageSize.getHeight() - 10,
      { align: "center" }
    );
  }

  doc.save(`${destination.toLowerCase().replace(/\s+/g, "-")}-itinerary.pdf`);
}
